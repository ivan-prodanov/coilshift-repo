#!/bin/bash
# direct-link/test/run.sh: the checks tools/build.sh can't make (it runs the harness kinds).
#
#   1. templates: our run/finish/log scripts equal install-car.sh's (at the gateway commit in
#      lib/gateway.sh) for the same inputs, apart from the binary paths and the generator name,
#      and agw's run script's direct-mode change (spelled out below);
#   2. shared files: direct-summon's copies of the shared files are byte-identical;
#   3. supervise.sh: marker wait, double-start refusal, stop order, take-it-back, on fakes only.
#
# Nothing here runs a real sv, iptables, kill, gdbus or runsvdir: supervise.sh runs under
# CSDK_FAKE_ROOT, where lib/common.sh only ever calls the fakes in test/fakes. The only signal
# sent is TERM to the supervise.sh this script started itself.
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
feature=$(cd "$here/.." && pwd)
repo=$(cd "$feature/.." && pwd)
DL=$feature/coilshift/io.github.ivan-prodanov.direct-link
DS=$repo/direct-summon/coilshift/io.github.ivan-prodanov.direct-summon
fails=0
ok()   { echo "ok   $*"; }
bad()  { echo "FAIL $*"; fails=$((fails + 1)); }
work=$(mktemp -d "${TMPDIR:-/tmp}/direct-link-test.XXXXXX")
trap 'rm -rf "$work"' EXIT

# shellcheck source=/dev/null
. "$DL/lib/gateway.sh"

# ---- 1. templates ----
inst=$work/install-car.sh
git -C "$repo" show "HEAD:gateway/deploy/install-car.sh" >"$inst" # the in-repo gateway source
back() {
    sed -e 's#/run/direct-link-bin/agw#/var/lib/airgapp-gw/agw#g' \
        -e 's#/run/direct-link-bin/camhelper#/var/lib/airgapp-camhelper/camhelper#g' \
        -e 's#/run/direct-summon-bin/summonhelper#/var/lib/airgapp-gw/summonhelper#g' \
        -e 's#Generated by Direct Link\.#Generated by install-car.sh.#' \
        -e 's#Generated by Direct Summon\.#Generated by install-car.sh.#' \
        -e 's#(apply Direct Link again)#(run install-car.sh --after-boot)#'
}
ours() { # FUNCTION ARGS... -> the generated variables, the installer's way
    ( CSDK_RUN=$work/run CSDK_PKG=test; export CSDK_RUN
      # shellcheck source=/dev/null
      . "$DL/lib/common.sh"
      "$@"
      case "$1" in
      gen_agw_scripts) printf '%s\n---- finish ----\n%s\n' "$AGW_RUN" "$AGW_FINISH" ;;
      gen_helper_scripts) printf '%s\n---- finish ----\n%s\n' "$HELPER_RUN" "$HELPER_FINISH" ;;
      gen_summon_scripts) printf '%s\n---- finish ----\n%s\n' "$SUMMON_RUN" "$SUMMON_FINISH" ;;
      log_run) ;;
      esac ) | back
}
same() { # NAME EXPECTED ACTUAL
    if [ "$2" = "$3" ]; then ok "template $1"
    else bad "template $1"; diff <(printf '%s\n' "$2") <(printf '%s\n' "$3") | sed 's/^/     /' || true; fi
}
pin=$(printf 'a%.0s' $(seq 64))
# agw's run script is the one deliberate departure (direct mode): the installer's, with the
# tailscale0 wait added and `serve -tailnet` instead of `serve -dial PI_IP:17101`. Its finish
# is still the installer's.
exp=$(AGW_SCRIPTS_ONLY=1 PI_IP=192.168.4.1 sh "$inst" ./agw | awk '
    /serve -dial "192\.168\.4\.1:17101"/ {
        print "if [ ! -e /sys/class/net/tailscale0 ]; then"
        print "\techo \"agw run: tailscale0 is not up yet (Tailscale); waiting\""
        print "\tsleep 5"
        print "\texit 1"
        print "fi"
        sub(/serve -dial "192\.168\.4\.1:17101"/, "serve -tailnet")
    }
    { print }')
same "agw (tailnet)" "$exp" "$(ours gen_agw_scripts)"
case "$(ours gen_agw_scripts)" in
*'-dial'*|*17101*) bad "agw run still names the Pi" ;;
*) ok "agw run names no Pi" ;;
esac
for w in pw-cat aplay; do
    for p in "" "$pin"; do
        exp=$(AGW_HELPER_RUN_ONLY=1 HELPER_WRITER=$w AUTHD_SHA256=$p sh "$inst")
        act=$(ours gen_helper_scripts "$w" "$p" | sed '/^---- finish ----$/,$d')
        same "camhelper run ($w${p:+, pin})" "$exp" "$act"
    done
done
# camhelper's finish and the log scripts have no print-only mode: take them from the source.
exp=$(sed -n '/^HELPER_FINISH=\$(cat <<EOF$/,/^EOF$/p' "$inst" | sed '1d;$d' |
      sed 's#\$HELPER_BIN#/var/lib/airgapp-camhelper/camhelper#; s#\$HELPER_STATE#/run/airgapp-camhelper-state#')
act=$(ours gen_helper_scripts pw-cat "" | sed '1,/^---- finish ----$/d')
same "camhelper finish" "$exp" "$act"
for p in "" "$pin"; do
    exp=$(AGW_SUMMON_SCRIPTS_ONLY=1 AUTHD_SHA256=$p sh "$inst")
    same "summonhelper${p:+ (pin)}" "$exp" "$(ours gen_summon_scripts "$p")"
done
exp=$(sh -c "$(sed -n '/^log_run() {$/,/^}$/p' "$inst"); log_run agw /var/lib/airgapp-gw/svlog/agw")
same "log run" "$exp" "$(ours log_run agw /var/lib/airgapp-gw/svlog/agw 'Direct Link')"

# ---- 1b. the egress lock on an update from 1.0 (fakes only) ----
# A 1.0 car has the Pi rule; apply's egress_lock must leave exactly the tailnet reply rule and
# the DROP, with the jump first in OUTPUT, and a second run must change nothing.
er=$work/egress
mkdir -p "$er/.fakes/state"
cp "$here"/fakes/* "$er/.fakes/"
printf 'AIRGAPP_GW_OUT\n' >"$er/.fakes/state/iptables.chains"
printf '%s\n' '-A OUTPUT -m owner --uid-owner 4950 -j AIRGAPP_GW_OUT' \
    '-A OUTPUT -m owner --uid-owner 1000 -j TESLA_EXAMPLE_OUT' \
    '-A AIRGAPP_GW_OUT -o wlan0 -d 192.168.4.1 -p tcp --dport 17101 -j ACCEPT' \
    '-A AIRGAPP_GW_OUT -j DROP' >"$er/.fakes/state/iptables.rules"
lock() {
    ( CSDK_FAKE_ROOT=$er CSDK_RUN=$work/run CSDK_PKG=test; export CSDK_FAKE_ROOT CSDK_RUN
      # shellcheck source=/dev/null
      . "$DL/lib/common.sh"
      egress_lock "$IPT" "$(egress_accept_rule)" )
}
want='-A OUTPUT -m owner --uid-owner 4950 -j AIRGAPP_GW_OUT
-A OUTPUT -m owner --uid-owner 1000 -j TESLA_EXAMPLE_OUT
-A AIRGAPP_GW_OUT -o tailscale0 -p tcp -m tcp --sport 17100 -m conntrack --ctstate ESTABLISHED -j ACCEPT
-A AIRGAPP_GW_OUT -j DROP'
if lock && [ "$(cat "$er/.fakes/state/iptables.rules")" = "$want" ]; then ok "egress lock: 1.0's Pi rule becomes the tailnet reply rule"
else bad "egress lock from 1.0"; sed 's/^/     /' "$er/.fakes/state/iptables.rules"; fi
before=$(cat "$er/.fakes/state/iptables.rules")
if lock && [ "$(cat "$er/.fakes/state/iptables.rules")" = "$before" ]; then ok "egress lock: a second apply changes nothing"
else bad "egress lock is not idempotent"; fi

# Tesla's firewall puts a rule above the jump: egress_keep moves the jump back to the top, once.
printf '%s\n' '-A OUTPUT -s 192.168.22.2/32 -o wlan1 -j ACCEPT' >"$er/.fakes/state/iptables.rules.top"
cat "$er/.fakes/state/iptables.rules.top" "$er/.fakes/state/iptables.rules" >"$er/.fakes/state/iptables.rules.n"
mv "$er/.fakes/state/iptables.rules.n" "$er/.fakes/state/iptables.rules"; rm -f "$er/.fakes/state/iptables.rules.top"
keep() {
    ( CSDK_FAKE_ROOT=$er CSDK_RUN=$work/run CSDK_PKG=test; export CSDK_FAKE_ROOT CSDK_RUN
      # shellcheck source=/dev/null
      . "$DL/lib/common.sh"
      egress_lock "$IP6T" >/dev/null 2>&1 # apply's IPv6 half, so only the IPv4 jump is out of place
      egress_keep )
}
first=$(grep '^-A OUTPUT' "$er/.fakes/state/iptables.rules" | head -n 1)
r1=$(keep); r2=$(keep)
if [ "$first" != '-A OUTPUT -m owner --uid-owner 4950 -j AIRGAPP_GW_OUT' ] && [ "$r1" = restored ] && [ -z "$r2" ] &&
   [ "$(grep '^-A OUTPUT' "$er/.fakes/state/iptables.rules" | head -n 1)" = '-A OUTPUT -m owner --uid-owner 4950 -j AIRGAPP_GW_OUT' ] &&
   [ "$(grep -c 'AIRGAPP_GW_OUT$' "$er/.fakes/state/iptables.rules")" = 1 ] &&
   grep -qx -- '-A OUTPUT -s 192.168.22.2/32 -o wlan1 -j ACCEPT' "$er/.fakes/state/iptables.rules"; then
    ok "egress keep: the jump goes back to the top once; Tesla's rule stays"
else bad "egress keep (r1=$r1 r2=$r2)"; sed 's/^/     /' "$er/.fakes/state/iptables.rules"; fi

# ---- 1c. the panel's pairing address (fakes only) ----
pr=$work/panelroot
mkdir -p "$pr/.fakes/state" "$work/prun"
cp "$here"/fakes/* "$pr/.fakes/"
pub() {
    ( CSDK_FAKE_ROOT=$pr CSDK_RUN=$work/prun CSDK_PKG=test; export CSDK_FAKE_ROOT CSDK_RUN
      # shellcheck source=/dev/null
      . "$DL/lib/common.sh"
      publish_car_host )
    cat "$work/prun/panel/car-host.txt" 2>/dev/null || true
}
printf '%s\n' '7: tailscale0    inet 100.100.1.1/32 scope global tailscale0\       valid_lft forever preferred_lft forever' \
    >"$pr/.fakes/state/ip.tailscale0"
[ "$(pub)" = 100.100.1.1 ] && ok "panel: the tailnet address is published" || bad "panel: address not published"
[ "$(pub)" = 100.100.1.1 ] && ok "panel: an unchanged address stays" || bad "panel: unchanged address"
printf '%s\n' '7: tailscale0    inet 100.128.0.1/32 scope global tailscale0' >"$pr/.fakes/state/ip.tailscale0"
[ -z "$(pub)" ] && ok "panel: an address outside the tailnet range is not published" || bad "panel: out-of-range address published"
: >"$pr/.fakes/state/ip.tailscale0"
pub >/dev/null; printf '%s\n' '7: tailscale0    inet 100.101.1.1/32 scope global tailscale0' >"$pr/.fakes/state/ip.tailscale0"
[ "$(pub)" = 100.101.1.1 ] && ok "panel: a new address replaces it" || bad "panel: new address"
rm -f "$pr/.fakes/state/ip.tailscale0"
[ -z "$(pub)" ] && ok "panel: no tailscale0, no address" || bad "panel: stale address kept without tailscale0"

# ---- 2. shared files ----
for f in lib/common.sh lib/csdk.sh lib/gateway.sh bin/supervise.sh; do
    if cmp -s "$DL/$f" "$DS/$f"; then ok "shared $f"; else bad "shared $f differs (run direct-link/sync.sh)"; fi
done

# ---- 3. supervise.sh ----
if [ -f "$here/supervise_test.sh" ]; then
    # shellcheck source=/dev/null
    . "$here/supervise_test.sh"
fi

[ "$fails" = 0 ] && echo "all ok" || { echo "$fails failed"; exit 1; }
