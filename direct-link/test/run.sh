#!/bin/bash
# direct-link/test/run.sh: the checks tools/build.sh can't make (it runs the harness kinds).
#
#   1. templates: our run/finish/log scripts equal install-car.sh's (at the gateway commit in
#      lib/gateway.sh) for the same inputs, apart from the binary paths and the generator name;
#   2. shared files: direct-summon's copies of the shared files are byte-identical;
#   3. supervise.sh: marker wait, double-start refusal, stop order, take-it-back, on fakes only.
#
# Nothing here runs a real sv, iptables, kill, gdbus or runsvdir: supervise.sh runs under
# CSDK_FAKE_ROOT, where lib/common.sh only ever calls the fakes in test/fakes. The only signal
# sent is TERM to the supervise.sh this script started itself.
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
feature=$(cd "$here/.." && pwd)
repo=$(cd "$feature/.." && pwd)
DL=$feature/coilshift/io.github.ivan-prodanov.direct-link
DS=$repo/direct-summon/coilshift/io.github.ivan-prodanov.direct-summon
fails=0
ok()   { echo "ok   $*"; }
bad()  { echo "FAIL $*"; fails=$((fails + 1)); }
work=$(mktemp -d "${TMPDIR:-/tmp}/direct-link-test.XXXXXX")
trap 'rm -rf "$work"' EXIT

# shellcheck source=/dev/null
. "$DL/lib/gateway.sh"

# ---- 1. templates ----
inst=$work/install-car.sh
git -C "$repo" show "HEAD:gateway/deploy/install-car.sh" >"$inst" # the in-repo gateway source
back() {
    sed -e 's#/run/direct-link-bin/agw#/var/lib/airgapp-gw/agw#g' \
        -e 's#/run/direct-link-bin/camhelper#/var/lib/airgapp-camhelper/camhelper#g' \
        -e 's#/run/direct-summon-bin/summonhelper#/var/lib/airgapp-gw/summonhelper#g' \
        -e 's#Generated by Direct Link\.#Generated by install-car.sh.#' \
        -e 's#Generated by Direct Summon\.#Generated by install-car.sh.#' \
        -e 's#(apply Direct Link again)#(run install-car.sh --after-boot)#'
}
ours() { # FUNCTION ARGS... -> the generated variables, the installer's way
    ( CSDK_RUN=$work/run CSDK_PKG=test; export CSDK_RUN
      # shellcheck source=/dev/null
      . "$DL/lib/common.sh"
      "$@"
      case "$1" in
      gen_agw_scripts) printf '%s\n---- finish ----\n%s\n' "$AGW_RUN" "$AGW_FINISH" ;;
      gen_helper_scripts) printf '%s\n---- finish ----\n%s\n' "$HELPER_RUN" "$HELPER_FINISH" ;;
      gen_summon_scripts) printf '%s\n---- finish ----\n%s\n' "$SUMMON_RUN" "$SUMMON_FINISH" ;;
      log_run) ;;
      esac ) | back
}
same() { # NAME EXPECTED ACTUAL
    if [ "$2" = "$3" ]; then ok "template $1"
    else bad "template $1"; diff <(printf '%s\n' "$2") <(printf '%s\n' "$3") | sed 's/^/     /' || true; fi
}
pin=$(printf 'a%.0s' $(seq 64))
for ip in 192.168.4.1 10.1.2.3; do
    exp=$(AGW_SCRIPTS_ONLY=1 PI_IP=$ip sh "$inst" ./agw)
    same "agw ($ip)" "$exp" "$(ours gen_agw_scripts "$ip")"
done
for w in pw-cat aplay; do
    for p in "" "$pin"; do
        exp=$(AGW_HELPER_RUN_ONLY=1 HELPER_WRITER=$w AUTHD_SHA256=$p sh "$inst")
        act=$(ours gen_helper_scripts "$w" "$p" | sed '/^---- finish ----$/,$d')
        same "camhelper run ($w${p:+, pin})" "$exp" "$act"
    done
done
# camhelper's finish and the log scripts have no print-only mode: take them from the source.
exp=$(sed -n '/^HELPER_FINISH=\$(cat <<EOF$/,/^EOF$/p' "$inst" | sed '1d;$d' |
      sed 's#\$HELPER_BIN#/var/lib/airgapp-camhelper/camhelper#; s#\$HELPER_STATE#/run/airgapp-camhelper-state#')
act=$(ours gen_helper_scripts pw-cat "" | sed '1,/^---- finish ----$/d')
same "camhelper finish" "$exp" "$act"
for p in "" "$pin"; do
    exp=$(AGW_SUMMON_SCRIPTS_ONLY=1 AUTHD_SHA256=$p sh "$inst")
    same "summonhelper${p:+ (pin)}" "$exp" "$(ours gen_summon_scripts "$p")"
done
exp=$(sh -c "$(sed -n '/^log_run() {$/,/^}$/p' "$inst"); log_run agw /var/lib/airgapp-gw/svlog/agw")
same "log run" "$exp" "$(ours log_run agw /var/lib/airgapp-gw/svlog/agw 'Direct Link')"

# ---- 2. shared files ----
for f in lib/common.sh lib/csdk.sh lib/gateway.sh bin/supervise.sh; do
    if cmp -s "$DL/$f" "$DS/$f"; then ok "shared $f"; else bad "shared $f differs (run direct-link/sync.sh)"; fi
done

# ---- 3. supervise.sh ----
if [ -f "$here/supervise_test.sh" ]; then
    # shellcheck source=/dev/null
    . "$here/supervise_test.sh"
fi

[ "$fails" = 0 ] && echo "all ok" || { echo "$fails failed"; exit 1; }
