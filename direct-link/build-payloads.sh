#!/bin/bash
# build-payloads.sh COMMIT AGW_SHA256 CAMHELPER_SHA256 SUMMONHELPER_SHA256
#
# Builds the two payload images from one gateway commit and wires them into both packages:
#   1. take the gateway source from this repo's gateway/ (committed: `git archive HEAD:gateway`;
#      COMMIT is the gateway commit it was added at, recorded as the build id) and run its
#      `make car` unchanged (-trimpath -buildvcs=false: the same bytes from any path) with the
#      local go1.26.2, nothing downloaded. gateway/ is the source of record here (its docs
#      and tests are scrubbed of the owner's identifiers, which does not change the binaries);
#   2. refuse unless the three binaries are the reviewed ones (the hashes given);
#   3. pack direct-link/payloads/direct-link-<build>.sqfs (agw, camhelper, BUILD) and
#      direct-summon/payloads/direct-summon-<build>.sqfs (summonhelper, BUILD), deterministically;
#   4. scan both images for leaks (tools/leakscan.sh with local.env's patterns, plus build paths);
#   5. write lib/gateway.sh (hashes, build id, the proven authd builds), each manifest's
#      payloads entry, and copy the shared files to direct-summon (sync.sh).
# Older images in the payloads dirs are removed: an older build lives on in git history.
set -euo pipefail

[ $# -eq 4 ] || { echo "usage: $0 COMMIT AGW_SHA256 CAMHELPER_SHA256 SUMMONHELPER_SHA256" >&2; exit 2; }
here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/.." && pwd)
TOOLCHAIN=go1.26.2
# authd builds the camera runbook's sign-in pre-check proved (step 2b). A new firmware's authd
# gets a row here only after that pre-check passes on it; then a new package version.
AUTHD_PINS="e0c74323da8f638b2d21d823cd989e0f6b43dfcf24b9db3e68aa9520057c1c0f 33d62d9e818afcb9b4a4af8cec6ecda2ff1801c5a667bd527e39a2b4f6f477e9"

die() { echo "build-payloads: $*" >&2; exit 1; }
sha() { shasum -a 256 "$1" | cut -d' ' -f1; }

build=$1
case "$build" in [0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f]) ;; *) die "COMMIT must be the 7-hex gateway commit" ;; esac
git -C "$repo" diff --quiet HEAD -- gateway && git -C "$repo" diff --cached --quiet -- gateway \
    || die "gateway/ has uncommitted changes: the build uses the committed tree"
want_agw=$2 want_cam=$3 want_sum=$4
w=$(mktemp -d "${TMPDIR:-/tmp}/direct-link-build.XXXXXX")
trap 'rm -rf "$w"' EXIT

# 1. build
mkdir -p "$w/src"
git -C "$repo" archive HEAD:gateway | tar -x -C "$w/src"
have=$(cd "$w/src" && GOTOOLCHAIN=local go env GOVERSION)
[ "$have" = "$TOOLCHAIN" ] || die "need $TOOLCHAIN, have $have"
(cd "$w/src" && GOTOOLCHAIN=local GOPROXY=off GOFLAGS=-mod=readonly make car >/dev/null)

# 2. the reviewed binaries
for pair in "agw:$want_agw" "camhelper:$want_cam" "summonhelper:$want_sum"; do
    b=${pair%%:*} want=${pair#*:}
    got=$(sha "$w/src/out/$b")
    [ "$got" = "$want" ] || die "$b is $got, not the reviewed $want"
done

# 3. images
printf 'build %s\ntoolchain %s\nagw %s\ncamhelper %s\nsummonhelper %s\n' \
    "$build" "$TOOLCHAIN" "$want_agw" "$want_cam" "$want_sum" >"$w/BUILD"
mkdir -p "$w/dl" "$w/ds"
cp "$w/src/out/agw" "$w/src/out/camhelper" "$w/BUILD" "$w/dl/"
cp "$w/src/out/summonhelper" "$w/BUILD" "$w/ds/"
chmod 0755 "$w/dl" "$w/ds" "$w/dl/agw" "$w/dl/camhelper" "$w/ds/summonhelper"
chmod 0644 "$w/dl/BUILD" "$w/ds/BUILD"
dl_img=$repo/direct-link/payloads/direct-link-$build.sqfs
ds_img=$repo/direct-summon/payloads/direct-summon-$build.sqfs
mkdir -p "$(dirname "$dl_img")" "$(dirname "$ds_img")"
rm -f "$repo"/direct-link/payloads/*.sqfs "$repo"/direct-summon/payloads/*.sqfs
for pair in "$w/dl:$dl_img" "$w/ds:$ds_img"; do
    mksquashfs "${pair%%:*}" "${pair#*:}" -comp gzip -all-root -noappend -no-xattrs \
        -mkfs-time 0 -all-time 0 -quiet -no-progress >/dev/null
done

# 4. leak scan: the publish gate's scanner (the car's identifiers come from local.env), plus
#    paths a non-trimmed build would carry.
EXTRA_LEAK='/usr/local/go/|/private/tmp/|/var/folders/' "$repo/tools/leakscan.sh" "$dl_img" "$ds_img" \
    || die "the images leak (above)"

# 5. lib/gateway.sh, manifests, shared files
pkg=$repo/direct-link/coilshift/io.github.ivan-prodanov.direct-link
cat >"$pkg/lib/gateway.sh" <<EOF
# gateway.sh: the gateway build in this package's image. Generated by direct-link/build-payloads.sh;
# identical in Direct Link and Direct Summon.
GW_BUILD=$build
GW_COMMIT=$build
GW_TOOLCHAIN=$TOOLCHAIN
AGW_SHA256=$want_agw
CAMHELPER_SHA256=$want_cam
SUMMONHELPER_SHA256=$want_sum
# authd builds whose sign-in the camera runbook's pre-check proved (2026.38.6, 2026.8.6).
AUTHD_PINS="$AUTHD_PINS"
EOF
setpayload() { # MANIFEST IMAGE
    python3 -I - "$1" "$2" "$(sha "$2")" "$(wc -c <"$2" | tr -d ' ')" <<'PY'
import json, sys, os
m, img, digest, size = sys.argv[1], sys.argv[2], sys.argv[3], int(sys.argv[4])
d = json.load(open(m))
d["payloads"] = [{"path": "payload/" + os.path.basename(img), "sha256": digest, "size": size}]
open(m, "w").write(json.dumps(d, indent=2) + "\n")
PY
}
setpayload "$pkg/coilshift.json" "$dl_img"
setpayload "$repo/direct-summon/coilshift/io.github.ivan-prodanov.direct-summon/coilshift.json" "$ds_img"
"$here/sync.sh"

echo "build $build: $(basename "$dl_img") $(sha "$dl_img" | cut -c1-12), $(basename "$ds_img") $(sha "$ds_img" | cut -c1-12); leak scan clean"
